import fs from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(new URL('../packages/cli/package.json', import.meta.url));
const ts = require('typescript');
const root = new URL('../', import.meta.url);
const output = new URL('apps/marketplace/public/', root);
const source = await fs.readFile(new URL('packages/shared/src/ui-translation.ts', root), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
await fs.mkdir(new URL('locales/', output), { recursive: true });
await fs.writeFile(new URL('i18n-core.js', output), '// Generated by scripts/build-web-locales.mjs from shared/src/ui-translation.ts.\n' + compiled);
await fs.copyFile(new URL('packages/shared/src/locales/en.json', root), new URL('locales/en.json', output));
console.log('Built shared browser translations.');
